// genicons generates fileicons_gen.go from Material Icon Theme's icon
// definitions (https://github.com/PKief/vscode-material-icon-theme, MIT).
// It writes the ext→icon map for a curated set of icons and copies the
// SVGs the map needs into assets/icons/.
//
// Usage: go run ./genicons <material-icons-repo> [<material-icons-repo>…]
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// icons we embed, by Material Icon Theme name.
var wanted = []string{
	"document", "file", "folder", "folder-git",
	"image", "pdf", "zip", "audio", "video", "font", "markdown",
	"html", "css", "sass", "javascript", "typescript", "react", "react_ts",
	"json", "yaml", "xml", "toml", "git", "python", "go", "rust", "java",
	"kotlin", "swift", "c", "cpp", "csharp", "php", "ruby", "shellcheck",
	"powershell", "docker", "terraform", "vue", "svelte", "scala",
	"perl", "lua", "dart", "groovy", "clojure", "haskell", "elixir",
	"erlang", "nim", "zig", "julia", "gradle", "maven", "log",
}

type iconDef struct {
	name           string
	fileExtensions []string
	fileNames      []string
}

var (
	nameRe  = regexp.MustCompile(`name:\s*'([^']+)'`)
	strRe   = regexp.MustCompile(`'([^']+)'`)
	extsRe  = regexp.MustCompile(`fileExtensions:\s*\[([^\]]*)\]`)
	namesRe = regexp.MustCompile(`fileNames:\s*\[([^\]]*)\]`)
)

// parseDefs pulls every { name, fileExtensions, fileNames } block out of
// the TS source. The files are data-only arrays of object literals, so a
// brace-scan with the regexes above is enough.
func parseDefs(src string) []iconDef {
	var defs []iconDef
	for i := 0; i < len(src); {
		open := strings.Index(src[i:], "{ name:")
		if open < 0 {
			break
		}
		open += i
		depth, j := 0, open
		for ; j < len(src); j++ {
			switch src[j] {
			case '{':
				depth++
			case '}':
				depth--
				if depth == 0 {
					goto done
				}
			}
		}
		break
	done:
		block := src[open : j+1]
		if m := nameRe.FindStringSubmatch(block); m != nil {
			def := iconDef{name: m[1]}
			if b := extsRe.FindStringSubmatch(block); b != nil {
				for _, s := range strRe.FindAllStringSubmatch(b[1], -1) {
					def.fileExtensions = append(def.fileExtensions, s[1])
				}
			}
			if b := namesRe.FindStringSubmatch(block); b != nil {
				for _, s := range strRe.FindAllStringSubmatch(b[1], -1) {
					def.fileNames = append(def.fileNames, s[1])
				}
			}
			defs = append(defs, def)
		}
		i = j + 1
	}
	return defs
}

func main() {
	if len(os.Args) < 2 {
		fmt.Fprintln(os.Stderr, "usage: genicons <material-icons-repo>…")
		os.Exit(2)
	}

	extToIcon := map[string]string{}
	nameToIcon := map[string]string{}
	needed := map[string]bool{}
	for _, w := range wanted {
		needed[w] = true
	}

	// Later repos override earlier ones: pass the theme's own dirs first
	// and overrides (languageAliases) last.
	for _, repo := range os.Args[1:] {
		src, err := os.ReadFile(filepath.Join(repo, "src/core/icons/fileIcons.ts"))
		if err != nil {
			fmt.Fprintln(os.Stderr, err)
			os.Exit(1)
		}
		for _, def := range parseDefs(string(src)) {
			if !needed[def.name] {
				continue
			}
			for _, ext := range def.fileExtensions {
				extToIcon[strings.ToLower(ext)] = def.name
			}
			for _, n := range def.fileNames {
				nameToIcon[strings.ToLower(n)] = def.name
			}
		}
	}

	// Every wanted icon with no mapping still ships, so the fallback look
	// stays consistent.
	var names []string
	for _, w := range wanted {
		names = append(names, w)
	}
	sort.Strings(names)

	outDir := "assets/icons"
	if err := os.MkdirAll(outDir, 0o755); err != nil {
		panic(err)
	}
	var svgNames []string
	for _, name := range names {
		var data []byte
		var err error
		for _, repo := range os.Args[1:] {
			data, err = os.ReadFile(filepath.Join(repo, "icons", name+".svg"))
			if err == nil {
				break
			}
			data = nil
		}
		if data == nil {
			// folder, folder-open and file are composed at build time by
			// the theme itself (generator/folderGenerator.ts et al) and
			// gitignored in the icons dir; compose them the same way.
			data = []byte(composedIcon(name))
		}
		if data == nil {
			fmt.Fprintf(os.Stderr, "warning: no SVG for %s\n", name)
			continue
		}
		if err := os.WriteFile(filepath.Join(outDir, name+".svg"), data, 0o644); err != nil {
			panic(err)
		}
		svgNames = append(svgNames, name)
	}

	// fileicons_gen.go: the maps and the embedded SVG registry.
	var b strings.Builder
	b.WriteString("// Code generated by genicons from Material Icon Theme")
	b.WriteString(" (github.com/PKief/vscode-material-icon-theme, MIT). DO NOT EDIT.\n\n")
	b.WriteString("package main\n\n")
	b.WriteString("import \"embed\"\n\n")
	b.WriteString("//go:embed assets/icons/*.svg\nvar iconFS embed.FS\n\n")
	fmt.Fprintf(&b, "// extIcon maps a lowercased file extension to an icon name.\nvar extIcon = map[string]string{\n")
	for _, ext := range sortedKeys(extToIcon) {
		fmt.Fprintf(&b, "\t%q: %q,\n", ext, extToIcon[ext])
	}
	b.WriteString("}\n\n")
	fmt.Fprintf(&b, "// fileNameIcon maps a lowercased file name to an icon name.\nvar fileNameIcon = map[string]string{\n")
	for _, n := range sortedKeys(nameToIcon) {
		fmt.Fprintf(&b, "\t%q: %q,\n", n, nameToIcon[n])
	}
	b.WriteString("}\n\n")
	b.WriteString("// iconSVGNames lists the icon names embedded under assets/icons/.\n")
	fmt.Fprintf(&b, "var iconSVGNames = []string{%s}\n\n", quoteJoin(svgNames))
	if err := os.WriteFile("fileicons_gen.go", []byte(b.String()), 0o644); err != nil {
		panic(err)
	}
	fmt.Printf("wrote fileicons_gen.go (%d extensions, %d file names, %d svgs)\n",
		len(extToIcon), len(nameToIcon), len(svgNames))
}

func sortedKeys[T any](m map[string]T) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

func quoteJoin(ss []string) string {
	parts := make([]string, len(ss))
	for i, s := range ss {
		parts[i] = fmt.Sprintf("%q", s)
	}
	return strings.Join(parts, ", ")
}

// The theme composes its base icons at build time from these paths and
